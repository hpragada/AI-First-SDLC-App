"""What each engine can actually DECIDE — the question two completeness proofs never asked (#4).

`ownership.verify_complete()` proves every one of the 55 criteria has an owner.
`gates.wcag.verify_complete()` proves every criterion is either asked of a designer or recorded
as deliberately not asked. Both are real guarantees and both were kept. Neither asks the third
question:

    can the owner we named actually perform the check?

For four tasks the answer for two criteria was no, and nothing said so. The registry recorded
1.4.10 Reflow and 1.4.11 Non-text Contrast as decided by a deterministic engine; the platform's
deterministic engine is axe-core; axe-core ships no rule for either. The words "a deterministic
engine can decide the typical case" — which is what the research report meant by RULE, and which
is true of both criteria in principle — were read as "axe does it". Nobody wrote the missing
rules because everybody believed they already existed.

This module is the answer, as data rather than as a belief:

  * `axe_criteria()` — what the pinned scanner covers, generated FROM axe itself
    (`runner/companion/assets/scanner_inventory.mjs`, regenerated by
    `python manage.py build_scanner_coverage`), never hand-written.
  * `platform_rule_criteria()` — what the platform measures with rules of its own, read from
    the modules that hold them rather than restated here.
  * `deciders_for()` — every engine that can settle one criterion, in one call.

`test_a11y_owner_capability` turns those into the assertion that was missing, and it fails by
name: *"1.4.10 is recorded as rule-decided and nothing checks it."* Run today against an axe
with a `wcag1410` rule removed, or against a registry that grows a fifteenth rule-owned
criterion, it fails immediately rather than in a client meeting.

**The inventory records the COMPANION's pinned axe, and that is the conservative choice.** A
client project shipping its own axe is scanned with theirs, which may cover more. What is
guaranteed is the floor; a guarantee measured against the most favourable installation would not
be one.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

DATASET_PATH = Path(__file__).resolve().parent / "data" / "scanner_coverage.json"

#: Where the inventory comes from, named here so the failure message can tell somebody what to
#: run. A stale file is the one way this guard could give a false assurance, so the path travels
#: with every error it raises.
INVENTORY_SCRIPT = "runner/companion/assets/scanner_inventory.mjs"
REBUILD_COMMAND = "python manage.py build_scanner_coverage"

#: The engines a criterion can be decided by, as the coverage ledger names them.
ENGINE_SCANNER = "rule"          # axe-core, whichever copy was resolved
ENGINE_PLATFORM = "page_rule"    # a deterministic rule the platform wrote itself
ENGINE_AI = "AI"                 # an element checker's judgment
ENGINE_AGENTIC = "agentic"       # the keyboard/interaction walk


class ScannerCoverageMissing(RuntimeError):
    """The committed inventory is absent or unreadable, so no capability can be proven."""


@lru_cache(maxsize=1)
def inventory() -> dict:
    """The committed inventory, read once per process. Never mutated."""
    try:
        return json.loads(DATASET_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ScannerCoverageMissing(
            f"the scanner coverage inventory at {DATASET_PATH} could not be read ({exc}). "
            f"Regenerate it with `{REBUILD_COMMAND}` — without it the platform cannot prove "
            f"that any rule-owned criterion is checked by anything."
        ) from exc


def axe_criteria() -> dict[str, tuple[str, ...]]:
    """{criterion: the axe rules tagged to it} under the six WCAG tags the platform scans with.

    Includes criteria outside Level A/AA — axe tags one rule to 2.1.3, which is Level AAA. Kept
    as axe reports it and filtered by the caller, because narrowing a vendor's own statement
    inside the reader of it is how a difference between two lists becomes invisible.
    """
    return {
        str(number): tuple(rules)
        for number, rules in (inventory().get("criteria") or {}).items()
    }


def platform_rule_criteria() -> dict[str, tuple[str, ...]]:
    """{criterion: our own deterministic rule ids} — what the platform measures itself.

    Read from the modules that hold the rules rather than listed again here. A second list would
    be a second thing to keep in step, and the whole failure this module exists to prevent was
    two lists nobody compared.
    """
    from . import journey_rules, page_rules

    return {
        "1.4.10": (page_rules.RULE_REFLOW,),
        "1.4.11": (page_rules.RULE_FIELD_BOUNDARY, page_rules.RULE_COMPONENT_BOUNDARY),
        "2.4.7": (journey_rules.RULE_OUTLINE_SUPPRESSED,),
        "4.1.3": (journey_rules.RULE_NO_LIVE_REGION,),
    }


def ai_criteria() -> dict[str, tuple[str, ...]]:
    """{criterion: the element checkers that judge it}."""
    from integrations.types import A11Y_CHECKER_CRITERIA

    out: dict[str, list[str]] = {}
    for checker, criteria in A11Y_CHECKER_CRITERIA.items():
        for number in criteria:
            out.setdefault(number, []).append(checker)
    return {number: tuple(sorted(checkers)) for number, checkers in out.items()}


def agentic_criteria() -> dict[str, tuple[str, ...]]:
    """{criterion: the journey checks that judge it}."""
    from integrations.types import A11Y_JOURNEY_CRITERIA

    out: dict[str, list[str]] = {}
    for checker, criteria in A11Y_JOURNEY_CRITERIA.items():
        for number in criteria:
            out.setdefault(number, []).append(checker)
    return {number: tuple(sorted(checkers)) for number, checkers in out.items()}


def deciders_for(number: str) -> dict[str, tuple[str, ...]]:
    """Every engine that can settle this criterion today, and what each brings.

    `{}` is the answer that matters: a criterion no engine can decide. For a criterion the
    registry gives to a human that is correct and expected; for one it gives to a machine it is
    the bug this module exists to make impossible to miss.
    """
    found: dict[str, tuple[str, ...]] = {}
    for engine, source in (
        (ENGINE_SCANNER, axe_criteria()),
        (ENGINE_PLATFORM, platform_rule_criteria()),
        (ENGINE_AI, ai_criteria()),
        (ENGINE_AGENTIC, agentic_criteria()),
    ):
        if entry := source.get(str(number)):
            found[engine] = entry
    return found


def deterministic_criteria() -> set[str]:
    """Every criterion something deterministic can decide — axe's rules and ours together.

    This is the set the registry's `owner="rule"` is a claim about, and comparing the two is the
    whole of `test_a11y_owner_capability`.
    """
    return set(axe_criteria()) | set(platform_rule_criteria())


def describe() -> str:
    """The inventory in words, for a failure message and for a person reviewing coverage."""
    data = inventory()
    return (
        f"{data.get('scanner', 'the scanner')} {data.get('version', '(unknown version)')} — "
        f"{data.get('rules_selected', '?')} of {data.get('rules_total', '?')} rules selected by "
        f"the tags {', '.join(data.get('tags') or [])}, touching "
        f"{len(data.get('criteria') or {})} criteria"
    )
